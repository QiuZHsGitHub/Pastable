import AppKit
import ApplicationServices
import ImageIO
import UniformTypeIdentifiers

@MainActor
final class Clipboard {
  static let shared = Clipboard()

  private let pasteboard: NSPasteboard
  private var changeCount: Int
  private var timer: Timer?
  private var lastCapturedHash: String?
  private var lastCapturedAt: Date?
  /// Incremented for every observed change (and for our own writes). Async
  /// normalization results from an older generation are thrown away.
  private var generation = 0
  private var didShowAccessibilityAlert = false

  nonisolated private static let supportedTypes: [NSPasteboard.PasteboardType] = [
    .fileURL, .html, .png, .rtf, .string, .tiff, .jpeg, .heic
  ]
  nonisolated private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .jpeg, .heic, .tiff]

  nonisolated private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
    .autoGenerated,
    .concealed,
    .transient,
    .fromPastable // Ignore self
  ]

  init(pasteboard: NSPasteboard = .general) {
    self.pasteboard = pasteboard
    self.changeCount = pasteboard.changeCount
  }

  // MARK: - Monitoring

  func start() {
    guard timer == nil else { return }
    changeCount = pasteboard.changeCount

    // 0.3s keeps quick copy/paste sequences from being missed, while still
    // being cheap. Using .common mode keeps polling alive during menu tracking
    // and window resizing, where a default-mode timer would pause.
    let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
      Task { @MainActor in
        self?.checkForChangesInPasteboard()
      }
    }
    timer.tolerance = 0.1
    RunLoop.main.add(timer, forMode: .common)
    self.timer = timer
  }

  func stop() {
    timer?.invalidate()
    timer = nil
  }

  private func checkForChangesInPasteboard() {
    let current = pasteboard.changeCount
    guard current != changeCount else { return }

    changeCount = current
    generation &+= 1
    let captureGeneration = generation
    let frontApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    #if DEBUG
    print("[Clipboard][change] count=\(current) frontApp=\(frontApp ?? "unknown")")
    #endif

    // Some apps write in several passes. Wait briefly and only accept the
    // snapshot if no newer change arrived in the meantime.
    Task { @MainActor [weak self] in
      try? await Task.sleep(nanoseconds: 120_000_000)
      guard let self, captureGeneration == self.generation else { return }
      guard self.pasteboard.changeCount == current else { return }
      self.processPasteboardSnapshot(generation: captureGeneration, frontApp: frontApp)
    }
  }

  private func processPasteboardSnapshot(generation captureGeneration: Int, frontApp: String?) {
    guard let raw = Self.snapshotContents(from: pasteboard) else { return }
    let observedChangeCount = pasteboard.changeCount

    Task.detached(priority: .userInitiated) { [weak self] in
      let normalized = Self.normalizedContents(raw)
      guard !normalized.isEmpty else { return }
      let hash = HistoryItem.computeContentHash(rawContents: normalized)

      await self?.commit(
        normalized,
        hash: hash,
        frontApp: frontApp,
        generation: captureGeneration,
        observedChangeCount: observedChangeCount
      )
    }
  }

  private func commit(
    _ contents: [RawContentSnapshot],
    hash: String,
    frontApp: String?,
    generation captureGeneration: Int,
    observedChangeCount: Int
  ) {
    guard captureGeneration == generation else { return }
    guard pasteboard.changeCount == observedChangeCount else { return }

    let now = Date()
    if let lastCapturedHash,
       let lastCapturedAt,
       lastCapturedHash == hash,
       now.timeIntervalSince(lastCapturedAt) < 1.0 {
      return
    }
    lastCapturedHash = hash
    lastCapturedAt = now

    guard let item = Self.makeItem(from: contents, frontmostApp: frontApp, hash: hash) else { return }

    #if DEBUG
    let bytes = contents.reduce(0) { $0 + ($1.value?.count ?? 0) }
    print("[Clipboard][store] types=\(contents.map { $0.type }.joined(separator: ",")) bytes=\(bytes) hash=\(hash.prefix(16))")
    #endif

    Storage.shared.addOrUpdate(item)
    AppState.shared.shouldScrollToTop = true
  }

  // MARK: - Snapshot helpers

  /// Read the pasteboard on the main thread and keep only representations the
  /// user asked us to save. Reading immediately (instead of 100ms later) avoids
  /// capturing a newer clipboard state with an older changeCount.
  nonisolated static func snapshotContents(from pasteboard: NSPasteboard) -> [RawContentSnapshot]? {
    guard let types = pasteboard.types, !types.isEmpty else { return nil }
    guard Set(types).isDisjoint(with: ignoredTypes) else { return nil }

    let enabled = enabledTypes()
    guard !enabled.isEmpty else { return nil }

    var results: [RawContentSnapshot] = []
    var seenTypes = Set<String>()

    for item in pasteboard.pasteboardItems ?? [] {
      let itemTypes = Set(item.types)

      // Don't turn a disabled file/image copy into a noisy text entry.
      if !Preferences.saveFiles && itemTypes.contains(.fileURL) { continue }
      if !Preferences.saveImages && !itemTypes.isDisjoint(with: imageTypes) { continue }

      for type in supportedTypes where enabled.contains(type) {
        guard let data = item.data(forType: type), !data.isEmpty else { continue }

        // Empty/whitespace-only text produces a blank "0 字" card. It carries
        // no information, so don't pollute the history with it.
        if type == .string {
          let text = String(data: data, encoding: .utf8) ?? ""
          guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { continue }
        }

        if type == .fileURL {
          results.append(RawContentSnapshot(type: type.rawValue, value: data))
          continue
        }

        guard !seenTypes.contains(type.rawValue) else { continue }
        seenTypes.insert(type.rawValue)
        results.append(RawContentSnapshot(type: type.rawValue, value: data))
      }
    }

    return results.isEmpty ? nil : results
  }

  /// Collapse multiple image representations into the smallest lossless one and
  /// make the ordering deterministic so identical copies hash identically.
  nonisolated static func normalizedContents(_ contents: [RawContentSnapshot]) -> [RawContentSnapshot] {
    var files: [RawContentSnapshot] = []
    var others: [RawContentSnapshot] = []
    var images: [String: Data] = [:]

    for content in contents {
      let type = NSPasteboard.PasteboardType(content.type)
      if type == .fileURL {
        files.append(content)
      } else if imageTypes.contains(type) {
        if let value = content.value, !value.isEmpty {
          images[content.type] = value
        }
      } else {
        others.append(content)
      }
    }

    var seenTypes = Set<String>()
    others = others.filter { seenTypes.insert($0.type).inserted }
    others.sort { $0.type < $1.type }

    files.sort { lhs, rhs in
      func absolute(_ content: RawContentSnapshot) -> String {
        guard let value = content.value,
              let url = URL(dataRepresentation: value, relativeTo: nil, isAbsolute: true) else { return "" }
        return url.absoluteString
      }
      return absolute(lhs) < absolute(rhs)
    }

    var selectedImage: RawContentSnapshot?
    for type in imageTypes {
      guard let data = images[type.rawValue] else { continue }
      selectedImage = RawContentSnapshot(type: type.rawValue, value: data)
      break
    }

    // Screenshots often arrive as uncompressed TIFF. Converting to PNG shrinks
    // the store dramatically (one real database had 365 MB of TIFF payloads).
    if let image = selectedImage,
       NSPasteboard.PasteboardType(image.type) == .tiff,
       let data = image.value,
       data.count > 64_000,
       let png = pngRepresentation(of: data),
       png.count < data.count {
      selectedImage = RawContentSnapshot(type: NSPasteboard.PasteboardType.png.rawValue, value: png)
    }

    var result = files
    if let selectedImage {
      result.append(selectedImage)
    }
    result.append(contentsOf: others)
    return result
  }

  static func makeItem(
    from contents: [RawContentSnapshot],
    frontmostApp: String?,
    hash: String? = nil
  ) -> HistoryItem? {
    let models = contents.compactMap { content -> HistoryItemContent? in
      guard let value = content.value else { return nil }
      return HistoryItemContent(type: content.type, value: value)
    }
    guard !models.isEmpty else { return nil }

    let item = HistoryItem(
      contents: models,
      contentHash: hash ?? HistoryItem.computeContentHash(rawContents: contents)
    )
    item.application = frontmostApp
    return item
  }

  nonisolated private static func enabledTypes() -> Set<NSPasteboard.PasteboardType> {
    var enabled = Set(supportedTypes)
    if !Preferences.saveText {
      enabled.subtract([.string, .html, .rtf])
    }
    if !Preferences.saveImages {
      enabled.subtract(imageTypes)
    }
    if !Preferences.saveFiles {
      enabled.remove(.fileURL)
    }
    return enabled
  }

  nonisolated private static func pngRepresentation(of data: Data) -> Data? {
    let sourceOptions = [kCGImageSourceShouldCache: false] as CFDictionary
    guard let source = CGImageSourceCreateWithData(data as CFData, sourceOptions),
          let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
      return nil
    }

    let output = NSMutableData()
    guard let destination = CGImageDestinationCreateWithData(
      output,
      UTType.png.identifier as CFString,
      1,
      nil
    ) else {
      return nil
    }

    CGImageDestinationAddImage(destination, image, nil)
    guard CGImageDestinationFinalize(destination) else { return nil }
    return output as Data
  }

  // MARK: - Copy & paste

  func copy(_ item: HistoryItem) {
    let contents = item.contentItems.filter { $0.value != nil }
    var pasteboardItems: [NSPasteboardItem] = []

    let stripFormatting = Preferences.removeFormatting && !item.isImage && !item.isFile
    if stripFormatting, let text = item.text {
      let pasteboardItem = NSPasteboardItem()
      pasteboardItem.setString(text, forType: .string)
      pasteboardItems.append(pasteboardItem)
    } else {
      // One item per file keeps "copy multiple files in Finder" working. The
      // previous implementation put every file URL in a single item, so all but
      // the last file were silently lost.
      for content in contents where content.type == NSPasteboard.PasteboardType.fileURL.rawValue {
        guard let data = content.value else { continue }
        let pasteboardItem = NSPasteboardItem()
        pasteboardItem.setData(data, forType: .fileURL)
        pasteboardItems.append(pasteboardItem)
      }

      let otherContents = contents.filter { $0.type != NSPasteboard.PasteboardType.fileURL.rawValue }
      if !otherContents.isEmpty {
        let pasteboardItem = NSPasteboardItem()
        for content in otherContents {
          guard let data = content.value else { continue }
          pasteboardItem.setData(data, forType: NSPasteboard.PasteboardType(content.type))
        }
        if !pasteboardItem.types.isEmpty {
          pasteboardItems.append(pasteboardItem)
        }
      }
    }

    // Mark the pasteboard so the polling loop ignores our own write. Attach the
    // marker to the first item instead of calling pasteboard.setString(), which
    // would create an extra item and break multi-file copies.
    pasteboardItems.first?.setString("", forType: .fromPastable)

    pasteboard.clearContents()
    if !pasteboardItems.isEmpty {
      _ = pasteboard.writeObjects(pasteboardItems)
    }

    changeCount = pasteboard.changeCount
    generation &+= 1
  }

  func paste() {
    guard Preferences.pasteAutomatically else { return }
    guard ensureAccessibility() else { return }

    // Force QWERTY keycode for V (kVK_ANSI_V = 9).
    let vCode = CGKeyCode(9)
    let source = CGEventSource(stateID: .combinedSessionState)
    source?.setLocalEventsFilterDuringSuppressionState(
      [.permitLocalMouseEvents, .permitSystemDefinedEvents],
      state: .eventSuppressionStateSuppressionInterval
    )

    guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true),
          let keyUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false) else {
      return
    }

    keyDown.flags = .maskCommand
    keyUp.flags = .maskCommand
    keyDown.post(tap: .cgSessionEventTap)
    keyUp.post(tap: .cgSessionEventTap)

    playSound()
  }

  /// Posting synthetic key events requires the Accessibility permission. Without
  /// it the key press is silently dropped, which looks like a broken app.
  private func ensureAccessibility() -> Bool {
    if AXIsProcessTrusted() { return true }

    guard !didShowAccessibilityAlert else { return false }
    didShowAccessibilityAlert = true

    NSApp.activate(ignoringOtherApps: true)
    let alert = NSAlert()
    alert.alertStyle = .warning
    alert.messageText = NSLocalizedString("accessibility.title", comment: "Accessibility permission required")
    alert.informativeText = NSLocalizedString("accessibility.message", comment: "Explain how to enable auto paste")
    alert.addButton(withTitle: NSLocalizedString("accessibility.open_settings", comment: "Open System Settings"))
    alert.addButton(withTitle: NSLocalizedString("common.cancel", comment: "Cancel"))

    if alert.runModal() == .alertFirstButtonReturn,
       let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
      NSWorkspace.shared.open(url)
    }

    return false
  }

  private func playSound() {
    guard Preferences.playSounds else { return }

    if let sound = NSSound(named: NSSound.Name("Tink")) {
      sound.play()
    } else {
      NSSound.beep()
    }
  }
}
